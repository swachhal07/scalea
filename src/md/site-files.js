// Site-level files for crawlers and AI agents: llms.txt, llms-full.txt, ai.txt, robots.txt,
// the markdown catalog and the Organization JSON-LD. All are built from src/seo.js,
// src/site.jsx and the markdown registry, so they can't drift apart.

import { ABOUT, ORIGIN, PRIVATE_PATHS } from '../seo.js';
import { SITE, SOCIAL } from '../site.jsx';
import { BUDGETS } from '../pages/StartProject.jsx';
import { abs, date, esc, link } from './format.js';
import { listMarkdownRoutes, renderMarkdown } from './registry.jsx';

const SYNC = (self) =>
  `# ${self}: keep in sync with ${['robots.txt', 'llms.txt', 'ai.txt'].filter((f) => f !== self).join(' and ')}. All three are generated by src/md/site-files.js.`;

// The markdown API sits under the otherwise-private /api/ and stays open to agents.
const MARKDOWN_API = '/api/md/';

const socials = () => SOCIAL.map((s) => s.href()).filter(Boolean);

// Training crawlers we let in. Blocking one only keeps our pages out of model training;
// the search and user-fetch bots below are what let answer engines cite us.
const SEARCH_BOTS = ['OAI-SearchBot', 'ChatGPT-User', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot', 'Perplexity-User'];
const TRAINING_ALLOWED = ['GPTBot', 'ClaudeBot', 'Google-Extended', 'Applebot-Extended', 'CCBot'];
const TRAINING_BLOCKED = ['Bytespider'];

export function robotsTxt() {
  const group = (agents, rules) => [...agents.map((a) => `User-agent: ${a}`), ...rules].join('\n');
  const open = ['Allow: /', `Allow: ${MARKDOWN_API}`, ...PRIVATE_PATHS.map((p) => `Disallow: ${p}`)];
  return [
    SYNC('robots.txt'),
    `# Site map for language models: ${abs('/llms.txt')}\n# AI usage policy: ${abs('/ai.txt')}`,
    group(['*'], open),
    `# AI search and user-requested fetches: always allowed, so answers can cite us.\n${group(SEARCH_BOTS, open)}`,
    `# AI training crawlers we allow.\n${group(TRAINING_ALLOWED, open)}`,
    `# AI training crawlers we block.\n${group(TRAINING_BLOCKED, ['Disallow: /'])}`,
    `Sitemap: ${abs('/sitemap.xml')}`,
  ].join('\n\n') + '\n';
}

export function llmsTxt() {
  const routes = listMarkdownRoutes();
  const line = (r) => `- ${link(r.path === '/' ? 'Home' : r.title.replace(/ — .*$/, ''), r.md)}: ${esc(r.description)}`;
  return [
    `# ${ABOUT.name}`,
    `> ${esc(ABOUT.description)}`,
    `${ABOUT.name} is based in ${ABOUT.location} and works with clients ${ABOUT.areaServed.toLowerCase()}. ` +
      `Work is quoted as fixed-scope proposals; the project form offers budgets from ${BUDGETS[0].toLowerCase()} to ${BUDGETS[BUDGETS.length - 2]}. ` +
      `Contact: ${SITE.email}, ${SITE.phone} (phone and WhatsApp).`,
    `## Core pages\n\n${routes.filter((r) => r.group === 'core').map(line).join('\n')}`,
    [
      '## Machine-readable',
      '',
      `- ${link('Full content', '/llms-full.txt')}: every page above as markdown, in one file`,
      `- ${link('Markdown catalog', '/api/md/_catalog')}: every markdown route as JSON`,
      `- ${link('Sitemap', '/sitemap.xml')}`,
      `- ${link('AI usage policy', '/ai.txt')}`,
    ].join('\n'),
    `## Optional\n\n${routes.filter((r) => r.group === 'legal').map(line).join('\n')}`,
  ].join('\n\n') + '\n';
}

const FULL_LIMIT = 500_000;

export function llmsFullTxt() {
  const parts = listMarkdownRoutes().map((r) => `---\n<!-- source: ${abs(r.path)} -->\n\n${renderMarkdown(r.path)}`);
  const text = [`# ${ABOUT.name} - full content`, `> ${esc(ABOUT.description)}`, `Generated: ${date(new Date())}`, ...parts].join('\n\n');
  if (text.length > FULL_LIMIT) console.warn(`llms-full.txt is ${text.length} characters, over the ${FULL_LIMIT} target`);
  return text;
}

export function aiTxt() {
  const included = listMarkdownRoutes().map((r) => r.path);
  return [
    SYNC('ai.txt'),
    '# AI usage policy for this site (ai-txt spec v1.1.1).',
    `[identity]\nname: ${ABOUT.name}\nurl: ${ORIGIN}/\ndescription: ${ABOUT.description}\ncontact: ${SITE.email}`,
    [
      '[permissions]',
      'summarise: allowed',
      'quote: allowed, with attribution',
      'cite: allowed',
      'index-for-search: allowed',
      'index-for-answers: allowed',
      'training: allowed for the crawlers allowed in /robots.txt',
    ].join('\n'),
    [
      '[restrictions]',
      'no-fabricated-quotes: do not attribute words to us that are not on this site',
      'no-fake-reviews: do not invent reviews, ratings, clients or results for us',
      'no-misattribution: do not present our content as your own',
      'no-private-data: do not collect or train on personal data people send us through forms or email',
    ].join('\n'),
    `[attribution]\nformat: ${ABOUT.name} (${ORIGIN}/<path>)\nlink-to: the canonical HTML page, not the .md version`,
    `[scope]\n${[...included, MARKDOWN_API].map((p) => `include: ${p}`).join('\n')}\n${PRIVATE_PATHS.map((p) => `exclude: ${p}`).join('\n')}`,
    `[contact]\nemail: ${SITE.email}\nphone: ${SITE.phone}`,
    `Last updated: ${date(new Date())}`,
  ].join('\n\n') + '\n';
}

export function catalog() {
  return {
    site: ABOUT.name,
    generated: new Date().toISOString(),
    routes: listMarkdownRoutes().map((r) => ({
      path: r.path,
      url: abs(r.path),
      markdown: abs(r.md),
      title: r.title,
      description: r.description,
      lastModified: r.updated.toISOString(),
    })),
  };
}

// Organization + WebSite JSON-LD for the home page, from the same facts as llms.txt and ai.txt.
export function organizationJsonLd() {
  const org = `${ORIGIN}/#org`;
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'ProfessionalService',
        '@id': org,
        name: ABOUT.name,
        url: `${ORIGIN}/`,
        logo: `${ORIGIN}/logo.png`,
        image: `${ORIGIN}/og.png`,
        description: ABOUT.description,
        email: SITE.email,
        telephone: SITE.phone,
        address: { '@type': 'PostalAddress', addressLocality: ABOUT.locality, addressCountry: ABOUT.country },
        areaServed: ABOUT.areaServed,
        sameAs: socials(),
        knowsAbout: ['Web development', 'Mobile app development', 'Search engine optimization', 'Paid advertising', 'App store optimization', 'Generative engine optimization'],
      },
      { '@type': 'WebSite', '@id': `${ORIGIN}/#website`, url: `${ORIGIN}/`, name: ABOUT.name, publisher: { '@id': org } },
    ],
  };
}
